def _doc_id(i: int) -> str:
    return f"KB{1000 + i}"


def generate(seed: int = 42) -> tuple[list[dict], list[dict]]:
    """返回 (documents, chunks)。切片按段落；embedding 待阶段2灌入。"""
    docs, chunks = [], []
    cid = 1
    for i, (title, source_type, tags, topic, paras) in enumerate(_KB[:N_KB_DOCS]):
        doc_id = _doc_id(i)
        content = "\n".join(paras)
        docs.append({
            "document_id": doc_id,
            "title": title,
            "source_type": source_type,
            "content": content,
            "tags": tags,
            "topic": topic,
            "created_at": "2024-05-01T09:00:00+08:00",
        })
        for pi, para in enumerate(paras):
            chunks.append({
                "chunk_id": f"C{cid:04d}",
                "document_id": doc_id,
                "chunk_text": para,
                "metadata": {
                    "title": title,
                    "tags": tags,
                    "topic": topic,
                    "chunk_index": pi,
                },
                # embedding 在阶段2 由生成器计算后回填，此处预置
                "embedding": None,
                "embedding_dim": 0,
                "created_at": "2024-05-01T09:00:00+08:00",
            })
            cid += 1
    return docs, chunks